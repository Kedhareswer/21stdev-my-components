// #region layout
function rng(seed: number) {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

const FRAME_SIZE = { polaroid: [1, 1.19], print: [1.3, 0.92], square: [0.86, 1.06] }

/*
 * Every position the photographs visit, from the size of the stage alone:
 * scattered across the table, tucked into the folder, fanned around it, and
 * flung off-screen on the way out. Pure, so it is tested by running it.
 */
export function layoutMemories(W: number, H: number, frames: string[], seed: number) {
  const r = rng(seed)
  const n = frames.length
  const narrow = W < 640
  const m = Math.max(10, Math.min(W, H) * 0.025)
  // On a landscape stage the fan needs a row of photos above and below the
  // folder (each about 0.32 of its width tall), so height caps the width.
  const fw = narrow ? W * 0.88 : Math.min(W * 0.56, 640, (H - m * 4) / 1.34)
  const fh = fw * 0.62
  const fx = W / 2
  const fy = H / 2 + fh * 0.04
  const pw = Math.max(84, Math.min(fw * 0.27, 176))

  const photos = frames.map((f) => {
    const s = FRAME_SIZE[f as keyof typeof FRAME_SIZE] || FRAME_SIZE.polaroid
    return { w: Math.round(pw * s[0]), h: Math.round(pw * s[1]) }
  })

  // Scattered: a jittered grid over the whole table, visited in random order,
  // so the mess covers the screen instead of clumping.
  const cols = Math.max(2, Math.round(Math.sqrt((n * W) / H)))
  const rows = Math.ceil(n / cols)
  const cells = Array.from({ length: cols * rows }, (_, i) => i)
  for (let i = cells.length - 1; i > 0; i--) {
    const j = Math.floor(r() * (i + 1))
    const t = cells[i]
    cells[i] = cells[j]
    cells[j] = t
  }
  const scatter = photos.map((p, i) => {
    const c = cells[i]
    const cw = (W - m * 2) / cols
    const ch = (H - m * 2) / rows
    return {
      x: m + cw * ((c % cols) + 0.5 + (r() - 0.5) * 0.7),
      y: m + ch * (Math.floor(c / cols) + 0.5 + (r() - 0.5) * 0.7),
      r: (r() - 0.5) * 36,
      s: 1 + r() * 0.08,
    }
  })

  // Tucked: standing in the folder, their tops peeking over its back edge.
  const tucked = photos.map((p, i) => {
    const u = n > 1 ? i / (n - 1) : 0.5
    const spread = fw * 0.5 + p.w * 0.1
    return {
      x: fx + (u - 0.5) * spread * 2 * 0.92 + (r() - 0.5) * p.w * 0.25,
      y: fy - fh * 0.5 + p.h * (0.12 + r() * 0.3),
      r: (r() - 0.5) * 16,
      s: 0.9,
    }
  })

  // Fanned: evenly round an ellipse that clears the folder, stretched to use
  // the free space, then held inside the stage.
  const rx = Math.max(fw / 2 + pw * 0.62, Math.min(W / 2 - pw * 0.72, fw / 2 + pw * 1.35))
  const ry = Math.max(fh / 2 + pw * 0.66, (H / 2 - pw * 0.62 - m) * 0.92)
  // Equal arc length rather than equal angle, or the photos pile up on
  // whichever side of the ellipse is flatter.
  const arc = [0]
  const STEPS = 360
  for (let k = 1; k <= STEPS; k++) {
    const a0 = ((k - 1) / STEPS) * Math.PI * 2
    const a1 = (k / STEPS) * Math.PI * 2
    arc.push(arc[k - 1] + Math.hypot(Math.cos(a1) * rx - Math.cos(a0) * rx, Math.sin(a1) * ry - Math.sin(a0) * ry))
  }
  const start = arc[STEPS] * 0.75
  let slots = photos.map((_, k) => {
    const target = (start + ((k + 0.5) / n) * arc[STEPS]) % arc[STEPS]
    let j = 1
    while (j < STEPS && arc[j] < target) j++
    const a = ((j - 1 + (target - arc[j - 1]) / (arc[j] - arc[j - 1] || 1)) / STEPS) * Math.PI * 2
    return { x: fx + Math.cos(a) * rx, y: fy + Math.sin(a) * ry, a }
  })
  // Portrait: there is no room beside the folder, so deal the photos into
  // two bands, one above it and one below.
  const tab = fw * 0.05
  if (H > W * 1.15) {
    const top = Math.ceil(n / 2)
    slots = photos.map((_, k) => {
      const upper = k < top
      const count = upper ? top : n - top
      const idx = upper ? k : k - top
      const cols = Math.min(3, count)
      const rowsN = Math.ceil(count / cols)
      const y0 = upper ? m : fy + fh / 2 + m
      const y1 = upper ? fy - fh / 2 - tab - m : H - m
      const cx = (idx % cols) + 0.5
      const cy = Math.floor(idx / cols) + 0.5
      const stagger = Math.floor(idx / cols) % 2 ? 0.18 : -0.18
      return {
        x: m + ((W - m * 2) / cols) * (cx + stagger * (cols > 1 ? 1 : 0)),
        y: y0 + ((y1 - y0) / rowsN) * cy,
        a: upper ? -Math.PI / 2 : Math.PI / 2,
      }
    })
  }
  // Hand out slots left-to-right in the order the photos stand in the folder,
  // so none of them cross over another on the way out.
  const bySlot = slots.map((_, k) => k).sort((a, b) => slots[a].x - slots[b].x)
  const byPhoto = tucked.map((_, i) => i).sort((a, b) => tucked[a].x - tucked[b].x)
  const fan = new Array(n)
  const order = new Array(n)
  byPhoto.forEach((pi, k) => {
    const s = slots[bySlot[k]]
    const p = photos[pi]
    // Push each photo out along its spoke until it clears the folder, so
    // nothing fanned ever sits over the lettering.
    let x = s.x
    let y = s.y
    const L = fx - fw / 2 - 6
    const R = fx + fw / 2 + 6
    const T = fy - fh / 2 - tab - 6
    const B = fy + fh / 2 + 6
    for (let t = 0; t < 40; t++) {
      const hit = x + p.w / 2 > L && x - p.w / 2 < R && y + p.h / 2 > T && y - p.h / 2 < B
      if (!hit) break
      x = fx + (x - fx) * 1.04
      y = fy + (y - fy) * 1.04
    }
    fan[pi] = {
      x: Math.min(W - m - p.w / 2, Math.max(m + p.w / 2, x)),
      y: Math.min(H - m - p.h / 2, Math.max(m + p.h / 2, y)),
      r: (r() - 0.5) * 14,
      s: 1,
    }
    order[pi] = Math.abs(Math.sin(s.a)) > 0.7 ? k * 0.5 : k
  })

  // Exit: thrown outward from the folder, past the edge of the stage.
  const far = Math.max(W, H) * 0.95
  const exit = fan.map((p, i) => {
    const dx = p.x - fx
    const dy = p.y - fy
    const d = Math.hypot(dx, dy) || 1
    return { x: fx + (dx / d) * far, y: fy + (dy / d) * far, r: fan[i].r * 4 + (dx > 0 ? 40 : -40), s: 1.1 }
  })

  return { folder: { x: fx, y: fy, w: fw, h: fh }, photos, scatter, tucked, fan, exit, order }
}
