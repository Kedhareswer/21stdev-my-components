/*
 * Memory Folder Preloader
 *
 * A landing preloader built like an old keepsake folder. Snapshots from
 * different years drop onto an oxblood table one at a time, developing as they
 * land, until the table is a mess of memories. Then they are swept together and
 * tucked into a cream file folder that rises over them, "Welcome" written
 * across its front in pointed-pen script. Hover the folder and the photographs
 * slide back out and fan around it; hover a photograph and it straightens up
 * and tells you where it was taken.
 *
 * Self-contained: no image, font or icon file. The twelve default photographs
 * are drawn in SVG, the script lettering is Pinyon Script (SIL OFL 1.1, © The
 * PinyonScript Project Authors) converted to outlines, and every style rule is
 * scoped to .mfp-*. Pass `memories` with `src` to use real photographs instead.
 */

